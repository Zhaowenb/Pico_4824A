const {chromium}=require(process.env.WAVEGUARD_PLAYWRIGHT_MODULE);
const assert=require('assert/strict'),fs=require('fs');
const base=process.env.WAVEGUARD_BASE_URL||'http://127.0.0.1:4877';
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[],checks=[];
 page.on('pageerror',e=>errors.push(e.stack));
 await page.goto(base+'/measure');
 await page.getByRole('button',{name:'参数设置',exact:true}).click();
 await page.waitForTimeout(450);
 const awg=await page.evaluate(()=>{const n=document.querySelector('#awgPreviewCanvas'),r=n.getBoundingClientRect();return {width:r.width,height:r.height,bitmap:[n.width,n.height]};});
 assert(awg.height>=150&&awg.bitmap[1]>0,JSON.stringify(awg));checks.push({awg});
 await page.goto(base+'/file-analysis');
 await page.evaluate(async()=>{document.querySelector('#analysisPath').value='F:/Project/01guided_waves/software/Pico_4824A_btf/data/A1.npz';await browseAnalysisPath();setAnalysisLens('filtered');});
 console.log('load',await page.evaluate(()=>({meta:document.querySelector('#analysisMeta').textContent,source:analysisSource,state:document.body.dataset.analysisState})),errors);
 await page.waitForFunction(()=>analysisResult && Object.keys(analysisResult.waveform).some(k=>k.endsWith(':filtered')));
 await page.evaluate(()=>setAnalysisLens('raw'));await page.waitForTimeout(400);
 const input=await page.evaluate(()=>analysisFilterPayload());assert.equal(input.enabled,false);checks.push({input});
 await page.evaluate(()=>setAnalysisLens('stft'));await page.waitForFunction(()=>timeFrequencyResult?.method==='stft');
 await page.evaluate(()=>{document.querySelector('#stftWindowUs').value='160';document.querySelector('#stftWindowUs').dispatchEvent(new Event('change',{bubbles:true}));setAnalysisLens('fft');setAnalysisLens('stft');});
 await page.waitForFunction(()=>Math.abs(timeFrequencyResult?.details?.window_us-160)<.01);
 checks.push({window:await page.evaluate(()=>timeFrequencyResult.details.window_us)});
 await page.evaluate(()=>{document.querySelector('#timeFrequencyMethod').value='wpd';document.querySelector('#timeFrequencyMethod').dispatchEvent(new Event('change',{bubbles:true}));});
 await page.waitForFunction(()=>timeFrequencyResult?.method==='wpd');checks.push({method:'wpd'});
 await page.evaluate(()=>{setAnalysisLens('cwt');setAnalysisLens('stft');});
 await page.waitForFunction(()=>timeFrequencyResult?.method==='stft'&&document.body.dataset.analysisState==='ready');
 await page.evaluate(()=>{setAnalysisSettingsOpen(true);document.querySelector('#analysisFilterEnabled').click();});
 await page.waitForFunction(()=>timeFrequencyState.status==='ready'&&JSON.parse(timeFrequencyState.key).filter.enabled);
 assert(await page.locator('#analysisFilterEnabled').isVisible());checks.push({explicitFilter:true});
 await page.screenshot({path:'.test-tmp/audit-repair-stft.png'});
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.evaluate(()=>setAnalysisLens('raw'));await page.waitForTimeout(400);
 assert.equal(await page.evaluate(()=>document.getAnimations().filter(a=>a.playState==='running').length),0);
 assert.deepEqual(errors,[]);
 fs.writeFileSync('.test-tmp/audit-repair-browser.json',JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({checks,errors},null,2));await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
